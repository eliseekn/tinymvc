declare(strict_types=1);

namespace App\Http\Middlewares;

/**
 * Manage HTTP CORS.
 */
class HttpCors
{
    public function handle(): void
    {
        response()->addHeaders([
            'Access-Control-Allow-Origin' => '*',
            'Access-Control-Allow-Headers' => '*',
            'Access-Control-Allow-Methods' => '*',
        ]);
    }
}
